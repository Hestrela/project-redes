import os
import sys
import requests
import urllib3
import pandas as pd
import random
from datetime import datetime, timedelta, timezone

# =====================================================================
# 1. Registro de Versões
# =====================================================================
print("=== Registro de Versões ===")
print(f"Python: {sys.version.split()[0]}")
print(f"Pandas: {pd.__version__}")
print(f"Requests: {requests.__version__}")
print(f"Urllib3: {urllib3.__version__}")
print("===========================\n")

# =====================================================================
# 2. Configuração Global (Parâmetros)
# =====================================================================
MEASUREMENT_ID = [66196984, 16437037, 112696111, 1001, 28095697, 7714918, 10001]

HORAS_COLETA = 168        # 7 dias completos (168 horas)
QUANTIDADE_PROBES = 5     # Quantidade exata a ser extraída por destino
FORMATO_TABELAR = "csv"
TIMEOUT_REQUISICAO = 120

fim_utc = datetime.now(timezone.utc)
inicio_utc = fim_utc - timedelta(hours=HORAS_COLETA)

start_unix = int(inicio_utc.timestamp())
stop_unix = int(fim_utc.timestamp())

print("=== Parâmetros de Tempo (UTC) ===")
print(f"Início da Coleta: {inicio_utc.isoformat()}")
print(f"Fim da Coleta:    {fim_utc.isoformat()}")
print(f"Unix Start:       {start_unix}")
print(f"Unix Stop:        {stop_unix}")
print("=================================\n")

# =====================================================================
# 3. Preparação do Diretório
# =====================================================================
try:
    from google.colab import drive
    drive.mount('/content/drive')
    caminho_base = '/content/drive/MyDrive/ripe_atlas/raw'
    os.makedirs(caminho_base, exist_ok=True)
    print(f"Diretório de destino inicializado: {caminho_base}\n")
except ImportError:
    print("Aviso: Execução local. Pastas locais serão utilizadas.")
    caminho_base = './Meu Drive/ripe_atlas/raw'
    os.makedirs(caminho_base, exist_ok=True)

# =====================================================================
# 4. Mapeamento de Âncoras Ativas (API RIPE)
# =====================================================================
print("Baixando mapeamento global de âncoras ativas da API RIPE...")
mapa_ancoras = {}
url_anchors = "https://atlas.ripe.net/api/v2/anchors/"

while url_anchors:
    try:
        resp = requests.get(url_anchors, timeout=TIMEOUT_REQUISICAO)
        resp.raise_for_status()
        dados = resp.json()

        for item in dados.get('results', []):
            prb_id = item.get('probe')
            is_disabled = item.get('is_disabled', False)

            if prb_id and not is_disabled:
                mapa_ancoras[prb_id] = {
                    'cidade': item.get('city', 'Desconhecida'),
                    'pais': item.get('country', 'XX')
                }
        url_anchors = dados.get('next')
    except requests.exceptions.RequestException as e:
        print(f"Erro ao obter dicionário de âncoras: {e}")
        break

print(f"Total de âncoras ativas mapeadas: {len(mapa_ancoras)}.\n")

# =====================================================================
# 5. Extração de Dados e Aplicação de Regras (Com Detalhamento Completo)
# =====================================================================
dados_consolidados = []

for m_id in MEASUREMENT_ID:
    print(f"--- Processando Medição ID: {m_id} ---")

    # 5.1. Identificar Destino
    url_meta = f"https://atlas.ripe.net/api/v2/measurements/{m_id}/"
    destino_alvo = "Desconhecido"

    try:
        res_meta = requests.get(url_meta, timeout=TIMEOUT_REQUISICAO)
        res_meta.raise_for_status()
        meta_json = res_meta.json()
        destino_alvo = meta_json.get('target') or meta_json.get('target_ip') or "Desconhecido"
        print(f"Destino Alvo: {destino_alvo}")
    except requests.exceptions.RequestException as e:
        print(f"Erro ao obter metadados da medição {m_id}: {e}")
        continue

    # 5.2. Extrair Resultados
    url_resultados = f"https://atlas.ripe.net/api/v2/measurements/{m_id}/results/"
    parametros = {"start": start_unix, "stop": stop_unix}

    try:
        res = requests.get(url_resultados, params=parametros, timeout=TIMEOUT_REQUISICAO)
        if res.status_code == 404:
            print(f"Medição {m_id}: Sem dados no período especificado. Operação ignorada.\n")
            continue
        res.raise_for_status()
        resultados_brutos = res.json()
    except requests.exceptions.RequestException as e:
        print(f"Falha na requisição dos resultados da medição {m_id}: {e}\n")
        continue

    # 5.3. Mapear cidades e sondas ativas
    sondas_na_medicao = set([r.get('prb_id') for r in resultados_brutos if r.get('prb_id')])
    cidades_encontradas = {}

    for prb in sondas_na_medicao:
        if prb in mapa_ancoras:
            nome_cidade = f"{mapa_ancoras[prb]['cidade']}, {mapa_ancoras[prb]['pais']}"
            if nome_cidade not in cidades_encontradas:
                cidades_encontradas[nome_cidade] = []
            cidades_encontradas[nome_cidade].append(prb)

    # 5.4. Aplicar filtro de quantidade mínima de sondas
    cidades_validas = {cidade: probes for cidade, probes in cidades_encontradas.items() if len(probes) >= QUANTIDADE_PROBES}

    if not cidades_validas:
        print(f"Medição {m_id} rejeitada: Nenhuma cidade atingiu a cota mínima de {QUANTIDADE_PROBES} âncoras ativas.")
        print("-" * 50)
        continue

    # 5.5. Seleção de origem e sondas
    cidade_escolhida = random.choice(list(cidades_validas.keys()))
    bolsao_sondas = cidades_validas[cidade_escolhida]
    probes_escolhidos = random.sample(bolsao_sondas, QUANTIDADE_PROBES)

    print("Origem selecionada:")
    print(f" * Cidade: {cidade_escolhida} (Âncoras disponíveis: {len(bolsao_sondas)})")
    print(f" * Sondas utilizadas (Restrito a {QUANTIDADE_PROBES}): {probes_escolhidos}")

    # 5.6. Reter dados completos (todas as colunas nativas do JSON) APENAS para os 5 probes selecionados
    registros_incluidos = 0
    for r in resultados_brutos:
        if r.get('prb_id') in probes_escolhidos:
            r['id_medicao'] = m_id
            r['destino_alvo'] = destino_alvo
            r['cidade_origem'] = cidade_escolhida

            dados_consolidados.append(r)
            registros_incluidos += 1

    print(f"Registros integrais extraídos da rota {cidade_escolhida} -> {destino_alvo}: {registros_incluidos}")
    print("-" * 50)

print("\nProcessamento concluído.")

# =====================================================================
# 6. Conversão, Tratamento e Exportação de Dados
# =====================================================================
if not dados_consolidados:
    print("Erro crítico: Nenhum dado atendeu aos critérios estabelecidos para a extração.")
    sys.exit()

# Flattening do JSON para extrair todas as colunas nativas
df = pd.json_normalize(dados_consolidados, sep="_")

# CORREÇÃO DO ERRO DE HASH:
# Converte listas e dicionários internos em strings para permitir operações
# de deduplicação do Pandas e salvamento do CSV sem corrupção.
for col in df.columns:
    if df[col].apply(type).eq(list).any() or df[col].apply(type).eq(dict).any():
        df[col] = df[col].astype(str)

# FORÇA A CRIAÇÃO DO DIRETÓRIO PARA EVITAR O OSERROR NO SALVAMENTO
os.makedirs(caminho_base, exist_ok=True)
caminho_final = os.path.join(caminho_base, f'medicoes_consolidadas.{FORMATO_TABELAR}')

try:
    if FORMATO_TABELAR == "csv":
        df.to_csv(caminho_final, index=False)
    else:
        df.to_parquet(caminho_final, index=False)
except Exception as e:
    print(f"Erro ao salvar arquivo: {e}")
    sys.exit()

# =====================================================================
# 7. Relatório de Estatísticas do Dataset
# =====================================================================
qtd_registros = len(df)
sondas_distintas = df['prb_id'].nunique() if 'prb_id' in df.columns else 0
destinos_distintos = df['destino_alvo'].nunique() if 'destino_alvo' in df.columns else 0

maximo_rtt = df['max'].max() if 'max' in df.columns and not df['max'].isnull().all() else 0.0
minimo_rtt = df['min'].min() if 'min' in df.columns and not df['min'].isnull().all() else 0.0

registros_duplicados = df.duplicated().sum()
valores_nulos = df.isnull().sum().sum()

print("\n" + "="*50)
print("RELATÓRIO DE ESTATÍSTICAS DO DATASET")
print("="*50)
print(f"Dimensões do DataFrame (linhas, colunas): ({df.shape[0]}, {df.shape[1]})")
print(f"Registros processados:               {qtd_registros}")
print(f"Alvos distintos:                     {destinos_distintos}")
print(f"Origens distintas:                   {sondas_distintas}")
print(f"Latência máxima (RTT):               {maximo_rtt:.2f} ms")
print(f"Latência mínima (RTT):               {minimo_rtt:.2f} ms")
print(f"Registros duplicados:                {registros_duplicados}")
print(f"Valores nulos presentes no dataset:  {valores_nulos}")
print("="*50)
print(f"\nExportação concluída. Arquivo gerado em: {caminho_final}")

